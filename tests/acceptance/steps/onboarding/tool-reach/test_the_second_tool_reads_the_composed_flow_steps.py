"""Steps for `onboarding/tool-reach/the_second_tool_reads_the_composed_flow.feature`.

BDL-083 S2h (RFC D13, BDL-UX #356). Every step scaffolds a real project with the
real ``setup-agentic-flow`` command and reads the files it wrote, or runs the real
``config-check`` command and reads its exit code and output. The one step that
writes files by hand is the one whose subject is the layout 9.0.0 left behind,
because no command of this release writes that layout any more.

The module is named ``test_*`` so default pytest collection picks the scenarios
up -- the acceptance suite runs inside ``uv run pytest``, not beside it.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

import pytest
from click.testing import CliRunner
from pytest_bdd import given, parsers, scenarios, then, when

from beadloom.onboarding.agentic_flow_setup import COMMAND_FILES
from beadloom.onboarding.composer import PROJECT_FLOW_DIRNAME
from beadloom.onboarding.flow_manifest import FLOW_MANIFEST_RELPATH, digest
from beadloom.onboarding.tool_reach import (
    cursor_command_rule_relpath,
    cursor_core_rule_relpath,
    rule_body,
)
from beadloom.services.cli import main

if TYPE_CHECKING:
    from pathlib import Path

scenarios("../../../onboarding/tool-reach/the_second_tool_reads_the_composed_flow.feature")

#: A Definition of Done the way an adopter writes one into the project layer. It
#: exists in no shipped fragment, so finding it in a composed body can only mean
#: the project layer reached that body.
_DOD = "## Definition of Done\n\nEvery bead runs `./check.sh` and quotes each exit code.\n"

#: The pointer 9.0.0 wrote for Cursor, in the shape that matters here: a file
#: under `.cursor/rules/` that carries no layer of the composed flow.
_POINTER_9_0_0 = (
    "# Beadloom agentic flow (Cursor orchestrator mode)\n\n"
    "Cursor runs the SAME flow as Claude Code, at parity.\n\n"
    "This file is generated by `beadloom setup-agentic-flow`.\n"
)


@pytest.fixture()
def world(tmp_path: Path) -> dict[str, Any]:
    """The one mutable bag the steps share, kept explicit rather than global."""
    return {"tmp": tmp_path, "projects": {}}


def _project(world: dict[str, Any], label: str) -> Path:
    root: Path = world["tmp"] / label
    root.mkdir()
    (root / "pyproject.toml").write_text(
        '[project]\nname = "acme"\nversion = "0.1.0"\n', encoding="utf-8"
    )
    fragment = root / PROJECT_FLOW_DIRNAME / "claude" / "CLAUDE.md"
    fragment.parent.mkdir(parents=True)
    fragment.write_text(_DOD, encoding="utf-8")
    return root


def _scaffold(root: Path, *tools: str) -> None:
    args = ["setup-agentic-flow", "--project", str(root), "--stack", "python"]
    for tool in tools:
        args += ["--tool", tool]
    result = CliRunner().invoke(main, args)
    assert result.exit_code == 0, result.output


def _scaffolded(world: dict[str, Any], *tools: str) -> Path:
    root = _project(world, "-".join(tools))
    _scaffold(root, *tools)
    world["projects"][tools] = root
    world["root"] = root
    return root


@given(parsers.parse('a project scaffolded for "{tool}" with a project fragment for the core'))
def _one_tool(world: dict[str, Any], tool: str) -> None:
    _scaffolded(world, tool)


@given(
    parsers.parse('a project scaffolded for "{tool}" with the same project fragment for the core')
)
def _the_other_tool(world: dict[str, Any], tool: str) -> None:
    _scaffolded(world, tool)


@given(
    parsers.parse(
        'a project scaffolded for both "{first}" and "{second}" '
        "with a project fragment for the core"
    )
)
def _both_tools(world: dict[str, Any], first: str, second: str) -> None:
    _scaffolded(world, first, second)


@given("its Cursor rules are the layout 9.0.0 wrote")
def _the_9_0_0_layout(world: dict[str, Any]) -> None:
    root: Path = world["root"]
    manifest_path = root / FLOW_MANIFEST_RELPATH
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    for rule in sorted((root / ".cursor" / "rules").glob("*.mdc")):
        relpath = str(rule.relative_to(root))
        payload["written"].pop(relpath, None)
        rule.unlink()
    pointer = root / ".cursor" / "rules" / "beadloom-flow.md"
    pointer.write_text(_POINTER_9_0_0, encoding="utf-8")
    payload["written"][".cursor/rules/beadloom-flow.md"] = digest(_POINTER_9_0_0)
    manifest_path.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


@when("config-check runs")
def _config_check(world: dict[str, Any]) -> None:
    world["check"] = CliRunner().invoke(main, ["config-check", "--project", str(world["root"])])


@then("the body of the Cursor core rule is byte-identical to the Claude CLAUDE.md")
def _core_identical(world: dict[str, Any]) -> None:
    claude_root: Path = world["projects"][("claude",)]
    cursor_root: Path = world["projects"][("cursor",)]
    claude_md = (claude_root / ".claude" / "CLAUDE.md").read_text(encoding="utf-8")
    rule = (cursor_root / cursor_core_rule_relpath()).read_text(encoding="utf-8")
    assert _DOD in claude_md
    assert rule_body(rule) == claude_md


@then("the body of every Cursor command rule is byte-identical to its Claude command")
def _commands_identical(world: dict[str, Any]) -> None:
    claude_root: Path = world["projects"][("claude",)]
    cursor_root: Path = world["projects"][("cursor",)]
    for name in COMMAND_FILES:
        command = (claude_root / ".claude" / "commands" / f"{name}.md").read_text(encoding="utf-8")
        rule = (cursor_root / cursor_command_rule_relpath(name)).read_text(encoding="utf-8")
        assert rule_body(rule) == command, name


@then(parsers.parse('every rule written under ".cursor/rules/" declares "{line}"'))
def _always_applied(world: dict[str, Any], line: str) -> None:
    rules = sorted((world["root"] / ".cursor" / "rules").glob("*.mdc"))
    assert len(rules) == 1 + len(COMMAND_FILES), rules
    for rule in rules:
        text = rule.read_text(encoding="utf-8")
        front_matter = text.split("---\n")[1]
        assert line in front_matter.splitlines(), rule.name


@then(parsers.parse('the pointer "{relpath}" is not written'))
def _no_pointer(world: dict[str, Any], relpath: str) -> None:
    assert not (world["root"] / relpath).exists()


@then(parsers.parse("config-check exits {code:d}"))
def _exit_code(world: dict[str, Any], code: int) -> None:
    assert world["check"].exit_code == code, world["check"].output


@then(parsers.parse('a finding names the tool "{tool}" and the layer "{layer}"'))
def _names_tool_and_layer(world: dict[str, Any], tool: str, layer: str) -> None:
    lines = [
        line
        for line in world["check"].output.splitlines()
        if f"`{tool}`" in line and f"{layer}" in line and "lacks" in line
    ]
    assert lines, world["check"].output


@then(parsers.parse('no finding names "{fragment}"'))
def _no_finding_names(world: dict[str, Any], fragment: str) -> None:
    assert fragment not in world["check"].output, world["check"].output
